'use strict';
const assert=require('node:assert/strict');
const {matchCharacters,claimAction,createEvidenceStore}=require('../lib/wclClaims.cjs');
const c={id:1,canonicalID:1,name:'测试',claimed:true,server:{name:'罗宁',region:{slug:'CN'}}};
const m={id:'m',name:'测试',server:'罗宁',status:'正式',user_id:null};
const match=(characters,members)=>matchCharacters(characters,members,'me');
assert.equal(match([c],[m])[0].status,'available');
assert.equal(match([{...c,claimed:false}],[m])[0].status,'unverified');
assert.equal(match([{...c,server:{name:'罗宁',region:{slug:'US'}}}],[m])[0].status,'unverified');
assert.equal(match([c],[{...m,server:''}])[0].status,'incomplete');
assert.equal(match([c],[m,{...m,id:'m2'}])[0].status,'ambiguous');
assert.equal(match([c],[{...m,server:'其他服'}])[0].status,'unmatched');
assert.equal(match([c],[{...m,user_id:'other'}])[0].status,'conflict');
assert.equal(match([c],[{...m,user_id:'me'}])[0].status,'owned');
assert.equal(match([c],[{...m,status:'离队'}])[0].status,'unmatched');
assert.equal(match([c,c],[m])[1].status,'duplicate');
for(const role of ['owner','editor'])for(const mode of ['free','approval','assign'])assert.equal(claimAction(mode,role),'claim');
assert.equal(claimAction('free','viewer'),'claim');assert.equal(claimAction('approval','viewer'),'request');
assert.equal(claimAction('assign','viewer'),'forbidden');assert.equal(claimAction('free',null),'forbidden');
let time=0;const store=createEvidenceStore({ttl:10,capacity:1,now:()=>time});
const id=store.issue('me','g',[c],1);
assert.equal(store.read(id,'other','g'),null);assert.equal(store.read(id,'me','other'),null);
const copy=store.read(id,'me','g');copy.characters[0].claimed=false;
assert.equal(store.read(id,'me','g').characters[0].claimed,true);
assert.throws(()=>store.issue('me','g',[c],1));time=10;assert.equal(store.read(id,'me','g'),null);
const next=store.issue('me','g',[c],1);store.revokeUser('me');assert.equal(store.read(next,'me','g'),null);
console.log('REQ185 core PASS: strict identity matching, claim modes, evidence isolation/expiry/capacity/revocation');
