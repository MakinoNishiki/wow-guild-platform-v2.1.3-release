'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '../..');
const manifestFile = path.join(root, 'js/decorModelManifest.js');
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(manifestFile, 'utf8'), context);
const legacy = Object.fromEntries(Object.entries(context.window.DecorModelManifest).filter(([, model]) => model.blendModes));
const structures = require('./structural-models.json');
const rows = require('../../data/task083/catalog-current-2335.json').filter(row => row.entry_type === 1);
const pairs = [];
for (const row of rows.sort((a, b) => a.record_id - b.record_id)) {
  const previous = legacy[row.record_id];
  const id = row.asset_id || structures[row.record_id]?.asset;
  const file = path.join(root, 'assets/decor-models', previous ? 'task084/' + row.record_id + '.glb' : 'catalog/' + id + '.glb');
  if (!id || !fs.existsSync(file)) throw new Error('Missing model for ' + row.record_id);
  if (!previous) pairs.push(row.record_id + ',' + id);
}
const lines = [];
for (let i = 0; i < pairs.length; i += 12) lines.push('    ' + pairs.slice(i, i + 12).join(','));
const output = [
  '// Generated by scripts/decor/index_catalog_models.cjs from packaged files and the CN decor catalog.',
  '(() => {', '  const models = ' + JSON.stringify(legacy, null, 2) + ';', '  const ids = [',
  lines.join(',\n'), '  ];', '  for (let i = 0; i < ids.length; i += 2) models[ids[i]] = { assetId: ids[i + 1] };',
  '  window.DecorModelManifest = Object.freeze(models);', '})();', ''
];
fs.writeFileSync(manifestFile, output.join('\n'));
