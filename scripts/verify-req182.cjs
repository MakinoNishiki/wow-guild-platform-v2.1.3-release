const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('server.js','utf8');
const start = source.indexOf('function wclActorSpecs(');
const end = source.indexOf('\n// 两个 WCL 端点', start);
const ctx = { window: {} }; vm.createContext(ctx);
vm.runInContext(source.slice(start, end),ctx);
vm.runInContext(fs.readFileSync('js/iconMap.js','utf8'),ctx);
const fight = (specs, startTime=0, ids=[1,2]) => ({friendlyPlayers:ids,friendlySpecs:specs,startTime});
const actual = ctx.wclActorSpecs([fight(['Arms','Holy']),fight(['Fury','Holy'],10),fight(['Fury','Holy'],20),fight([null,'Holy']),fight(['Arms'],30)],1);
assert.equal(actual.length,2); assert.equal(actual[0].name,'Fury'); assert.equal(actual[0].bossFights,2);
assert.equal(ctx.wclActorSpecs([fight(['Fury','Holy'],10),fight(['Arms','Holy'],20)],1)[0].name,'Arms');
