const assert = require('node:assert/strict');
const path = require('node:path');

module.exports = async ({author,guest,db,sessions,base,pass,output}) => {
  const id = 126;
  const card = author.locator('.dh-card[data-rid="126"]');
  const stat = key => card.locator('[data-count=' + key + ']');
  await author.goto(base + '/#/house/decor');
  await author.locator('#dhSearch').fill('卷起来的卷轴');
  await card.getByRole('button',{name:'点赞',exact:true}).click();
  await card.locator('.dh-heart[aria-pressed=true]').waitFor();
  assert.equal(await stat('likes').innerText(),'1');
  assert.equal(await stat('views').innerText(),'0');
  await author.reload();
  await author.locator('#dhSearch').fill('卷起来的卷轴');
  await card.locator('.dh-heart[aria-pressed=true]').waitFor();
  await card.getByRole('button',{name:'取消点赞'}).click();
  await card.locator('.dh-heart[aria-pressed=false]').waitFor();
  pass('图鉴卡片空心/实心点赞、重开状态和撤销，卡片操作不计详情浏览');
  await card.locator('[data-add]').click();
  await card.getByRole('button',{name:'查看方案单'}).waitFor();
  await author.waitForFunction(()=>document.querySelector('[data-rid="126"] [data-count=favorites]')?.textContent==='1');
  assert.equal(await author.locator('#dhNavPlanBadge').innerText(),'1');
  assert.equal(await author.locator('#dhPlanToggle').count(),0);
  await card.getByRole('button',{name:'查看方案单'}).click();
  await author.locator('#dhPpSave').waitFor();
  assert.ok(await author.locator('#dhNavPlanBadge').isHidden());
  assert.match(await author.locator('.dh-pp-table').innerText(),/卷起来的卷轴/);
  await author.locator('#dhPpSave').click();
  await author.getByText('方案单已保存',{exact:true}).waitFor();
  await author.locator('[data-ia-key=decor]:visible').click();
  await author.locator('#dhSearch').fill('卷起来的卷轴');
  await card.getByRole('button',{name:'选方案'}).click();
  const picker = author.locator('.dh-plan-target-dialog');
  await picker.locator('select').selectOption('new');
  await picker.locator('[name=newName]').fill('第二份采购单');
  await picker.getByRole('button',{name:'确认加入'}).click();
  await picker.waitFor({state:'detached'});
  const favoriteCount = await db.query('select favorites from decor_item_totals where record_id=$1',[id]);
  assert.equal(Number(favoriteCount.rows[0].favorites),1);
  assert.equal((await db.query('select i.qty from decor_plan_items i join decor_plans p on p.id=i.plan_id where p.user_id=$1 and i.record_id=$2',[sessions[0].user.id,id])).rowCount,2);
  pass('家具收藏即时存入方案单、侧栏红点查看后消失、已有方案打开、选新方案、一个账号多个方案收藏仅计一人');
  await card.locator('.dh-name').click();
  const dialog = author.locator('.dh-modal');
  const preview = dialog.getByRole('button',{name:'点击游戏内预览'});
  const note = dialog.locator('.dh-game-preview-note');
  assert.equal(await note.innerText(),'');
  await preview.click();
  await dialog.locator('.dh-game-preview-note[data-state=success]').waitFor();
  assert.match(await note.innerText(),/已复制。在游戏聊天框粘贴并按回车即可预览/);
  assert.match(await author.evaluate(()=>navigator.clipboard.readText()),/PreviewHousing/);
  const box = await preview.boundingBox(), after = await note.boundingBox();
  assert.ok(after.y >= box.y + box.height + 5);
  await dialog.locator('.dh-game-preview').screenshot({path:path.join(output,'preview-success.png')});
  await author.evaluate(()=>Object.defineProperty(navigator.clipboard,'writeText',{configurable:true,value:async()=>{throw Error('denied')}}));
  await preview.click();
  assert.equal(await note.getAttribute('data-state'),'manual');
  assert.ok(await dialog.locator('.dh-game-preview-command').isVisible());
  await author.evaluate(()=>delete navigator.clipboard.writeText);
  await author.locator('.dh-modal-close').click();
  pass('点游戏内预览确实复制命令；绿字成功提示与按钮上下分开，剪贴板被拒显示金色手动复制提示');
  await guest.goto(base+'/#/house/decor');
  await guest.locator('#dhSearch').fill('卷起来的卷轴');
  const publicCard = guest.locator('.dh-card[data-rid="126"]');
  await guest.waitForFunction(()=>document.querySelector('[data-rid="126"] [data-count=favorites]')?.textContent==='1');
  assert.equal(await publicCard.locator('[data-count=views]').innerText(),'1');
  await publicCard.getByRole('button',{name:'点赞'}).click();
  await guest.locator('#authOverlay').waitFor();
  await author.locator('#dhSearch').fill('');
  for (const width of [1366,1920]) {
    await author.setViewportSize({width,height:width===1366?768:1080});
    await author.locator('.dh-card').first().scrollIntoViewIfNeeded();
    await author.locator('.dh-card').first().screenshot({path:path.join(output,'card-'+width+'.png')});
  }
  pass('访客卡片可读三项汇总，点赞进入登录；1366 和 1920 两档已截图');
};
