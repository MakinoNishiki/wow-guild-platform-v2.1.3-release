// Real Chrome + disposable PostgreSQL/PostgREST through verify-req203-web.cjs --suite=supplies.
'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
module.exports = async ({author,guest,other,db,sessions,api,base,pass,output}) => {
  const workTitle = '家具清单与私有用量验收';
  const supply = async (action,session,data) => {
    const response = await fetch(base+'/api/housing-build-supplies/'+action+(action==='read'?'?id='+data.id:''),{
      method:action==='read'?'GET':'POST',headers:{'Content-Type':'application/json',...(session?{Authorization:'Bearer '+session.access_token}:{})},
      ...(action==='read'?{}:{body:JSON.stringify(data)})});
    return {status:response.status,data:await response.json()};
  };
  const mine = async id => (await api('mine?v=2&id='+id,sessions[0])).data.rows[0];
  const payload = row => ({id:row.id,revision:row.revision,title:row.title,description:row.description,blueprint_code:row.blueprint_code,
    code_public:row.code_public,allow_copy:row.allow_copy,published:row.published,screenshots:row.image_ids.map(id=>({id})),
    preset_tags:row.preset_tags,custom_tags:row.custom_tags,furniture_items:row.furniture_items});
  const detail = async (page,id) => { const url=base+'/#/house/community/'+id; if(page.url()===url) await page.reload(); else await page.goto(url); await page.locator('.hbf-detail').waitFor();
    try { await page.waitForFunction(()=>!document.querySelector('.hbf-detail input')?.disabled && !document.querySelector('.hbf-detail')?.textContent.includes('正在读取图鉴')); }
    catch(error) {throw new Error(error.message+' · '+await page.locator('.hbf-detail').innerText());} };
  for(const role of ['anon','authenticated']) {
    const access=(await db.query("select has_table_privilege($1,'housing_build_supplies','select') or has_function_privilege($1,'save_housing_build_supply(uuid,uuid,integer,jsonb)','execute') as allowed",[role])).rows[0];
    assert.equal(access.allowed,false);
  }
  await author.goto(base+'/#/house/community/mine');
  await author.locator('#hbCreate').click();
  await author.locator('#hbTitle').fill(workTitle);
  await author.locator('#hbDescription').fill('作者自愿附用量；私有数量不会公开。');
  await author.locator('#hbPublish').click();
  await author.locator('#housingBuildEditor').waitFor({state:'hidden'});
  const initial=(await api('mine?v=2',sessions[0])).data.rows.find(row=>row.title===workTitle);
  assert.deepEqual(initial.furniture_items,[]);
  await detail(guest,initial.id);
  assert.match(await guest.locator('.hbf-detail').innerText(),/尚未附家具清单/);
  pass('空家具清单可发布，公开页说明清单未提供，不凭蓝图码生成数量');
  await author.locator('.hb-work').filter({has:author.getByRole('heading',{name:workTitle,exact:true})}).getByRole('button',{name:'编辑作品',exact:true}).click();
  await author.locator('#hbFurnitureSearch').fill('卷起来的卷轴');
  await author.locator('[data-add-furniture="126"]').click();
  await author.locator('#hbFurniture tr[data-record-id="126"] input').fill('3');
  await author.locator('#hbFurnitureSearch').fill('银月城大型平台');
  await author.locator('[data-add-furniture="2105"]').click();
  await author.locator('#hbFurniture tr[data-record-id="2105"] input').fill('2');
  await author.locator('#hbPublish').click();
  await author.locator('#housingBuildEditor').waitFor({state:'hidden'});
  let row=await mine(initial.id);
  assert.deepEqual(row.furniture_items,[{record_id:126,quantity:3},{record_id:2105,quantity:2}]);
  const stored=(await db.query('select furniture_items from housing_builds where id=$1',[row.id])).rows[0];
  assert.deepEqual(stored.furniture_items,row.furniture_items);
  pass('真实点击编辑、图鉴搜索添加两种家具及数量、保存后数据库与作者列表回读一致');
  await detail(guest,row.id);
  assert.match(await guest.locator('.hbf-detail').innerText(),/2 种可用量未知/);
  assert.equal(await guest.locator('.hbf-detail input').count(),0);
  const name=guest.locator('.hbf-detail tr[data-record-id="126"] a');
  assert.equal(await name.innerText(),'卷起来的卷轴',await guest.locator('.hbf-detail').innerText());
  await name.hover();
  await guest.locator('.hbf-source-popover').waitFor();
  assert.match(await guest.locator('.hbf-source-popover').innerText(),/商人|来源|任务/);
  assert.match(await guest.locator('.hbf-source-popover').innerText(),/价格以游戏内为准/);
  await guest.screenshot({path:path.join(output,'supplies-hover-1366.png')});
  await name.click();
  await guest.locator('.dh-modal-overlay.show').waitFor();
  assert.match(await guest.locator('.dh-modal-overlay.show').innerText(),/卷起来的卷轴/);
  assert.match(guest.url(),/house\/decor\/item\/126/);
  await guest.goBack(); await guest.locator('.hbf-detail').waitFor();
  pass('游客可悬浮读取复用图鉴来源/地点/参考价格，并点入同站对应家具详情、返回作品');
  await detail(author,row.id);
  const input=id=>author.locator('.hbf-detail input[data-available="'+id+'"]');
  await input(126).fill('1');
  assert.equal(await author.locator('[data-missing="126"]').innerText(),'2');
  assert.equal(await author.locator('[data-missing="2105"]').innerText(),'未知');
  await input(2105).fill('0');
  await author.locator('.hbf-detail').getByRole('button',{name:'保存我的可用量'}).click();
  await author.locator('.hbf-detail').getByText(/我的可用量已保存/).waitFor();
  assert.deepEqual((await supply('read',sessions[0],{id:row.id})).data.available,{'126':1,'2105':0});
  await detail(author,row.id);
  assert.equal(await input(126).inputValue(),'1'); assert.equal(await input(2105).inputValue(),'0');
  await author.screenshot({path:path.join(output,'supplies-known-1920.png')});
  await detail(other,row.id);
  assert.equal(await other.locator('input[data-available="126"]').inputValue(),'');
  assert.equal(await other.locator('[data-missing="126"]').innerText(),'未知');
  pass('本人可用量保存并刷新保留；显式0计为缺件、空值未知；另一账号不读取本人的可用量');
  await author.route('**/api/housing-build-supplies/save',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({message:'验收模拟断网，输入已保留'})}));
  await input(126).fill('6');
  await author.locator('.hbf-detail').getByRole('button',{name:'保存我的可用量'}).click();
  await author.locator('.hbf-detail').getByText(/验收模拟断网/).waitFor();
  assert.equal(await input(126).inputValue(),'6');
  assert.deepEqual((await supply('read',sessions[0],{id:row.id})).data.available,{'126':1,'2105':0});
  await author.unroute('**/api/housing-build-supplies/save');
  await input(2105).fill('');
  await author.locator('.hbf-detail').getByRole('button',{name:'保存我的可用量'}).click();
  await author.locator('.hbf-detail').getByText(/我的可用量已保存/).waitFor();
  assert.equal(await author.locator('[data-missing="126"]').innerText(),'0');
  assert.equal(await author.locator('[data-missing="2105"]').innerText(),'未知');
  let saved=(await supply('read',sessions[0],{id:row.id})).data;
  assert.deepEqual(saved.available,{'126':6});
  assert.equal((await supply('save',sessions[0],{id:row.id,revision:1,available:{'126':6}})).data.revision,saved.revision);
  assert.equal((await supply('save',sessions[0],{id:row.id,revision:1,available:{'126':4}})).status,409);
  pass('保存失败保留输入和旧数据库；成功重试、清空恢复未知、足量缺件为0；重试幂等、旧版本冲突拦截');
  assert.equal((await supply('read',null,{id:row.id})).status,401);
  assert.equal((await supply('save',sessions[1],{id:row.id,revision:0,available:{'126':2},user_id:sessions[0].user.id})).status,400);
  for(const value of [-1,1.5,10000,'2']) assert.equal((await supply('save',sessions[0],{id:row.id,revision:saved.revision,available:{'126':value}})).status,400);
  assert.equal((await supply('save',sessions[0],{id:row.id,revision:saved.revision,available:{'999999':1}})).status,409);
  for(const furniture_items of [[{record_id:126,quantity:0}],[{record_id:126,quantity:1},{record_id:126,quantity:2}],[{record_id:126,quantity:1.5}]])
    assert.equal((await api('save-v2',sessions[0],{...payload(row),furniture_items})).status,400);
  assert.equal((await api('save-v2',sessions[0],{...payload(row),furniture_items:[{record_id:999999,quantity:1}]})).status,409);
  const publicData=(await api('gallery?v=2&id='+row.id,null)).data.rows[0];
  assert.equal(Object.hasOwn(publicData,'available'),false); assert.equal(Object.hasOwn(publicData,'user_id'),false);
  pass('匿名、伪造拥有者、非法数字、重复家具、未收录编号均拦截；公开作品不含私人可用量');
  const legacy=payload(row); delete legacy.furniture_items; delete legacy.preset_tags; delete legacy.custom_tags;
  const legacyResult=await api('save-v2',sessions[0],{...legacy,description:'旧接口修改仍保留清单'});
  assert.equal(legacyResult.status,200); row=await mine(row.id);
  assert.deepEqual(row.furniture_items,stored.furniture_items);
  const noTags=payload(row); delete noTags.preset_tags; delete noTags.custom_tags;
  assert.equal((await api('save-v2',sessions[0],{...noTags,furniture_items:[{record_id:126,quantity:4}]})).status,200);
  row=await mine(row.id); assert.deepEqual(row.furniture_items,[{record_id:126,quantity:4}]);
  pass('旧保存接口继续保留清单；带清单不带标签的兼容请求也可更新');
  await author.goto(base+'/#/house/community/mine');
  await author.locator('.hb-work').filter({has:author.getByRole('heading',{name:workTitle,exact:true})}).getByRole('button',{name:'编辑作品',exact:true}).click();
  await author.locator('.hbf-bulk summary').click();
  await author.setViewportSize({width:1366,height:768});
  const bulk=author.locator('#hbFurnitureBulk');
  await bulk.fill('[[3,126,3],[3,126,2]]');
  await author.getByRole('button',{name:'解析清单预览',exact:true}).click();
  assert.match(await author.locator('.hbf-bulk').innerText(),/重复/);
  assert.equal(await author.locator('#hbFurniture tr[data-record-id="126"] input').inputValue(),'4');
  await bulk.fill('[[1,126,88],[2,126,77],[5,2105,66],[3,126,3],[3,2105,2],[3,999999,1]]');
  await author.getByRole('button',{name:'解析清单预览',exact:true}).click();
  assert.match(await author.locator('.hbf-bulk').innerText(),/可附 2 种家具，共 5 件/);
  for(const type of [1,2,5]) assert.match(await author.locator('.hbf-bulk').innerText(),new RegExp('类型 '+type+'：1 行'));
  assert.match(await author.locator('.hbf-bulk').innerText(),/跳过未收录家具编号：999999/);
  await author.locator('.hbf-bulk-preview').scrollIntoViewIfNeeded();
  const previewBounds=await author.locator('.hbf-bulk-preview').boundingBox();
  assert.ok(previewBounds.x>=0 && previewBounds.x+previewBounds.width<=1366);
  await author.screenshot({path:path.join(output,'supplies-bulk-preview-1366.png')});
  assert.equal(await author.locator('#hbFurniture tr[data-record-id="126"] input').inputValue(),'4');
  await author.locator('#hbPublish').click();
  assert.match(await author.locator('#hbFormError').innerText(),/尚未确认/);
  await author.getByRole('button',{name:'确认附入清单',exact:true}).click();
  assert.equal(await author.locator('#hbFurniture tr[data-record-id="126"] input').inputValue(),'3');
  assert.equal(await author.locator('#hbFurniture tr[data-record-id="2105"] input').inputValue(),'2');
  await author.locator('#hbPublish').click(); await author.locator('#housingBuildEditor').waitFor({state:'hidden'});
  row=await mine(row.id); assert.deepEqual(row.furniture_items,[{record_id:126,quantity:3},{record_id:2105,quantity:2}]);
  pass('原生三元组批量预览只纳入类型3；1/2/5即使编号碰撞也跳过，未知编号不猜测；重复报错保留清单，确认后真实保存回读');
  await author.locator('.hb-work').filter({has:author.getByRole('heading',{name:workTitle,exact:true})}).getByRole('button',{name:'编辑作品',exact:true}).click();
  await author.locator('#hbFurniture tr[data-record-id="126"] input').fill('5');
  await author.locator('#hbFurniture tr[data-record-id="126"]').getByRole('button',{name:'移除'}).click();
  await author.locator('#hbFurniture tr[data-record-id="2105"]').getByRole('button',{name:'移除'}).click();
  await author.locator('#hbPublish').click(); await author.locator('#housingBuildEditor').waitFor({state:'hidden'});
  row=await mine(row.id); assert.deepEqual(row.furniture_items,[]);
  await detail(other,row.id); assert.match(await other.locator('.hbf-detail').innerText(),/尚未附家具清单/);
  assert.equal((await api('save-v2',sessions[0],{...payload(row),published:false})).status,200);
  assert.equal((await supply('read',sessions[1],{id:row.id})).status,404);
  assert.equal((await supply('save',sessions[1],{id:row.id,revision:0,available:{}})).status,404);
  pass('真实编辑移除最后一项并回读为空；作品撤回后其他账号不能读取或保存可用量');
};
